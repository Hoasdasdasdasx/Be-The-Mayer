// Keep the editable UI modules separate, but ship a portable HTML document.
// Socket.IO is still provided by the real game server; no game state is faked.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const template = read('client/index.template.html');
const css = read('public/styles.css');
const ui = read('public/ui.js').replace(/^export /gm, '');
const importLine = /^import \{[^\n]+\} from '\.\/ui\.js';\r?\n/;
const appSource = read('public/app.js');
if (!importLine.test(appSource)) throw new Error('Update the client build for the new app import structure.');
const app = appSource.replace(importLine, 'const esc = escapeHtml;\n');
if (/^\s*(import|export)\s/m.test(ui + app)) throw new Error('Unbundled module dependency in the client.');
const script = `document.addEventListener('DOMContentLoaded', () => {\n'use strict';\n${ui}\n${app}\n});`;
const output = template
  .replace('  <!-- INLINE_STYLES -->', () => `  <!-- Generated by npm run build; edit client/index.template.html and public source files. -->\n  <style>\n${css.replace(/<\/style/gi, '<\\/style')}\n  </style>`)
  .replace('  <!-- INLINE_APP -->', () => `  <script>\n${script.replace(/<\/script/gi, '<\\/script')}\n  </script>`);
if (process.argv.includes('--check')) {
  if (read('public/index.html') !== output) {
    console.error('public/index.html is stale. Run npm run build.');
    process.exitCode = 1;
  } else console.log('Portable HTML is up to date.');
} else {
  fs.writeFileSync(path.join(root, 'public/index.html'), output);
  console.log(`Built public/index.html (${Buffer.byteLength(output)} bytes).`);
}
